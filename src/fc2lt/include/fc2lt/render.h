// render.h -- stage 5: a Translation -> the text of a C++ header.
//
//   renderFunction    a plain function   inline std::complex<double> NAME(double x, double y, ...)
//   renderRegistered  the pipeline style: ampgen::NAME::eval(const ampflow::Args&) plus a descriptor that tells the runner,
//                     BY NAME, which inputs and which SLHA entries the amplitude needs
#pragma once
#include <sstream>
#include <string>
#include "ast.h"
#include "emitter.h"

namespace fc2lt {

// ---- output: plain function -------------------------------------------------------------------------------------
inline std::string renderFunction(const Translation& t, const std::string& functionName) {
    if (!t.slha.empty() || t.usesDelta || t.usesMu2)
        throw Error("this amplitude reads SLHA[...] or Runner[...] values; generate it with --registry");
    std::ostringstream o;
    o << "// Generated by fc2lt from FeynCalc output -- do not edit by hand.\n"
      << "// Invariants and SQUARED masses are passed to LoopTools unchanged (LoopTools expects m^2).\n"
      << "#pragma once\n#include <cmath>\n#include <complex>\n#include \"clooptools.h\"\n\n"
      << "inline std::complex<double> " << functionName << "(";
    for (std::size_t i = 0; i < t.params.size(); ++i) o << (i ? ", " : "") << "double " << t.params[i];
    o << ") {\n    return " << t.body << ";\n}\n";
    return o.str();
}

// ---- output: pipeline style ------------------------------------------------------------------------------------------
// The amplitude plus a descriptor telling the runner (by NAME) what it needs:
//   inputs : free symbols the runner supplies per scan point (s, t, ...)
//   slha   : SLHA card entries it reads (MASS[24], SMINPUTS[1], ...)
// so values are bound once, here, instead of by string matching at run time.
inline std::string cppString(const std::string& s) {                  // symbol keys like SMP["m_t"] contain quotes
    std::string r = "\"";
    for (char c : s) { if (c == '"' || c == '\\') r += '\\'; r += c; }
    return r + "\"";
}

inline std::string renderRegistered(const Translation& t, const std::string& name) {
    std::ostringstream o;
    o << "// Generated by fc2lt from FeynCalc output -- do not edit by hand.\n"
      << "// Invariants and SQUARED masses are passed to the loop-integral backend unchanged.\n"
      << "#pragma once\n#include <cmath>\n#include <complex>\n#include \"clooptools.h\"\n"
      << "#include \"ampflow/amplitude.h\"\n\n"
      << "namespace ampgen {\nnamespace " << name << " {\n\n"
      << "inline std::complex<double> eval([[maybe_unused]] const ampflow::Args& ampflow_args) {\n";
    for (std::size_t i = 0; i < t.params.size(); ++i)
        o << "    const double " << t.params[i] << " = ampflow_args.input[" << i << "];\n";
    for (std::size_t i = 0; i < t.slha.size(); ++i)
        o << "    const double slha_" << i << " = ampflow_args.slha[" << i << "];   // " << t.slha[i].where() << "\n";
    if (t.usesDelta) o << "    const double rt_delta = ampflow_args.delta;\n";
    if (t.usesMu2)   o << "    const double rt_mu2 = ampflow_args.mu2;\n";
    o << "    return " << t.body << ";\n}\n\n"
      << "inline ampflow::Amplitude descriptor() {\n"
      << "    return ampflow::Amplitude{\n        " << cppString(name) << ",\n        {";
    for (std::size_t i = 0; i < t.symbols.size(); ++i) o << (i ? ", " : "") << cppString(t.symbols[i]);
    o << "},\n        {";
    for (std::size_t i = 0; i < t.slha.size(); ++i) {
        o << (i ? ", " : "") << "{" << cppString(t.slha[i].block) << ", {";
        for (std::size_t k = 0; k < t.slha[i].key.size(); ++k) o << (k ? ", " : "") << t.slha[i].key[k];
        o << "}}";
    }
    o << "},\n        [](const ampflow::Args& a) { return eval(a); }};\n}\n\n"
      << "}  // namespace " << name << "\n}  // namespace ampgen\n";
    return o.str();
}

}  // namespace fc2lt
